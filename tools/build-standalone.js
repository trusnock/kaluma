/* build-standalone.js — inline the PIO Workbench demo into ONE self-contained
 * HTML file (demo/standalone.html) that you can double-click to open, no server.
 *
 * Why a build step instead of hand-editing?
 *   The live demo (demo/index.html) loads its CSS, the offline bundle, and app.js
 *   as separate <link>/<script> files. Browsers BLOCK external ES-module files
 *   over file:// (CORS), but INLINE module scripts are allowed — and app.js uses
 *   top-level await, so it must stay a module. Inlining everything keeps it a
 *   module AND makes the single file openable from disk.
 *
 * It prefers the LIVE repo source (../src/modules/rp2/rp2.js + tests/rp2.asm.test.js)
 * when you're serving from the repo, and falls back to the offline bundle
 * (demo/_bundle.js, base64) otherwise — same as the live page. So the standalone
 * file is correct whether or not the repo files are present.
 *
 *   node tools/build-standalone.js
 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DEMO = path.join(ROOT, "demo");

const read = (p) => fs.readFileSync(p, "utf8");
const css = read(path.join(DEMO, "style.css"));
const bundle = read(path.join(DEMO, "_bundle.js")); // sets self.__KALUMA_DEMO_BUNDLE__
const app = read(path.join(DEMO, "app.js"));
let html = read(path.join(DEMO, "index.html"));

// Sanity: never inline a closing-tag literal (would break HTML/JS parsing).
for (const [name, text] of [["style.css", css], ["_bundle.js", bundle], ["app.js", app]]) {
  if (/<\s*\/\s*script/i.test(text)) throw new Error(`</script> found in ${name} — inlining unsafe`);
}
if (/<\s*\/\s*style/i.test(css)) throw new Error("</style> found in style.css — inlining unsafe");

// Inline the stylesheet, then the offline bundle, then app.js (kept as an
// inline ES module so its top-level await still works over file://).
html = html.replace(
  /<link\s+rel="stylesheet"\s+href="\.\/style\.css"\s*\/>/i,
  () => `<style>\n${css}\n</style>`
);
// The bundle <script> stays external-relative; replace with the inline version.
html = html.replace(
  /<script\s+src="\.\/_bundle\.js"\s*><\/script>/i,
  () => `<script>\n${bundle}\n</script>`
);
html = html.replace(
  /<script\s+type="module"\s+src="\.\/app\.js"\s*><\/script>/i,
  () => `<script type="module">\n${app}\n</script>`
);

// Make sure every external reference is gone (font links may stay — they degrade).
const leftover = [
  ...html.matchAll(/<script\s+[^>]*src="[^"]*"/g),
  ...html.matchAll(/<link\s+[^>]*href="\.\/[^"]*\.css"/g),
];
if (leftover.length) {
  throw new Error("standalone still references external assets:\n" + leftover.map((m) => m[0]).join("\n"));
}

// Standalone badge so it's obvious this is the portable single-file build.
html = html.replace(
  /<title>(.*?)<\/title>/i,
  (m, t) => `<title>${t} — standalone</title>`
);
html = html.replace(
  /<body>/i,
  () => `<body>
<!-- standalone.html — self-contained build of the PIO Workbench demo.
     Generated by tools/build-standalone.js from demo/ (css + offline bundle + app.js).
     Double-click to open; no web server required. -->`
);

const out = path.join(DEMO, "standalone.html");
fs.writeFileSync(out, html);
console.log(`✓ wrote ${path.relative(ROOT, out)}  (${(html.length / 1024).toFixed(1)} kB)`);
console.log(`  inlined: style.css (${(css.length/1024).toFixed(1)}kB), _bundle.js (${(bundle.length/1024).toFixed(1)}kB), app.js (${(app.length/1024).toFixed(1)}kB)`);
